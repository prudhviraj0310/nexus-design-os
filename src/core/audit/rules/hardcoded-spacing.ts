import { AuditFinding, AuditRule } from '../types';

export const hardcodedSpacingRule: AuditRule = {
  id: 'RULE-004-HARDCODED-SPACING',
  name: 'Disallow Non-Standard Hardcoded Spacing',
  description: 'Flags arbitrary raw pixel spacing values in CSS/styles that bypass the spacing token scale.',
  defaultSeverity: 'info',
  evaluate({ filePath, content }) {
    const findings: AuditFinding[] = [];
    const lines = content.split('\n');

    // Matches e.g. padding: 13px; margin-top: 27px; gap: 19px;
    const spacingPropRegex = /\b(padding|margin|gap)(-[a-z]+)?\s*:\s*([^;]+);/g;

    lines.forEach((lineText, index) => {
      if (lineText.includes('Generated by NovaDesign')) return;

      let match: RegExpExecArray | null;
      while ((match = spacingPropRegex.exec(lineText)) !== null) {
        const value = match[3].trim();
        // Check if value contains raw px values not divisible by 4 (standard scale check)
        const pxMatches = value.match(/(\d+)px/g);
        if (pxMatches) {
          for (const px of pxMatches) {
            const num = parseInt(px, 10);
            if (num > 0 && num % 4 !== 0) {
              findings.push({
                ruleId: 'RULE-004-HARDCODED-SPACING',
                severity: 'info',
                message: `Arbitrary non-scale spacing "${px}" detected in "${match[0]}". Expected values adhering to the 4px or 8px spacing scale.`,
                filePath,
                line: index + 1,
                column: match.index + 1,
                evidence: lineText.trim(),
                suggestedFix: `Align to nearest scale token (e.g. ${Math.round(num / 4) * 4}px or var(--spacing-*)).`,
                automatedFixAvailable: false,
              });
            }
          }
        }
      }
    });

    return findings;
  },
};
