import { AuditFinding, AuditRule } from '../types.js';

export const unknownTokensRule: AuditRule = {
  id: 'RULE-002-UNKNOWN-TOKEN',
  name: 'Disallow Unknown Tokens',
  description: 'Flags CSS variables or token references that do not exist in the active design system.',
  defaultSeverity: 'error',
  evaluate({ filePath, content, tokens }) {
    const findings: AuditFinding[] = [];
    const lines = content.split('\n');

    // Set of known CSS variable names
    const knownVars = new Set<string>();
    for (const t of tokens) {
      knownVars.add(`--${t.path.replace(/\./g, '-')}`);
    }

    const varRegex = /var\(\s*(--[a-zA-Z0-9_-]+)\s*\)/g;

    lines.forEach((lineText, index) => {
      if (lineText.includes('Generated by NovaDesign')) return;

      let match: RegExpExecArray | null;
      while ((match = varRegex.exec(lineText)) !== null) {
        const varName = match[1];
        if (!knownVars.has(varName)) {
          findings.push({
            ruleId: 'RULE-002-UNKNOWN-TOKEN',
            severity: 'error',
            message: `Unrecognized design token reference "${varName}". It is not defined in the design system.`,
            filePath,
            line: index + 1,
            column: match.index + 1,
            evidence: lineText.trim(),
            suggestedFix: `Define "${varName}" in your token system or use an existing valid token.`,
            automatedFixAvailable: false,
          });
        }
      }
    });

    return findings;
  },
};
