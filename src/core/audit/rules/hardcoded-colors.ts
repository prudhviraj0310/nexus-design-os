import { AuditFinding, AuditRule } from '../types';

export const hardcodedColorsRule: AuditRule = {
  id: 'RULE-001-HARDCODED-COLOR',
  name: 'Disallow Hardcoded Colors',
  description: 'Flags raw hex, rgb, or hsl color values that should use design tokens instead.',
  defaultSeverity: 'warning',
  evaluate({ filePath, content, tokens }) {
    const findings: AuditFinding[] = [];
    const lines = content.split('\n');

    // Build reverse map of hex -> token path for suggestions
    const colorMap = new Map<string, string>();
    for (const t of tokens) {
      if (t.category === 'color' && typeof t.resolvedValue === 'string' && t.resolvedValue.startsWith('#')) {
        colorMap.set(t.resolvedValue.toLowerCase(), t.path);
      }
    }

    const hexRegex = /#([0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})\b/g;

    lines.forEach((lineText, index) => {
      // Ignore token definitions file itself or comments
      if (lineText.includes('Generated by NovaDesign') || lineText.trim().startsWith('//') || lineText.trim().startsWith('/*')) {
        return;
      }

      let match: RegExpExecArray | null;
      while ((match = hexRegex.exec(lineText)) !== null) {
        const hex = match[0].toLowerCase();
        const matchingToken = colorMap.get(hex);
        const suggestedFix = matchingToken
          ? `Replace "${match[0]}" with token "var(--${matchingToken.replace(/\./g, '-')})"`
          : `Replace "${match[0]}" with an appropriate design token from your color palette`;

        findings.push({
          ruleId: 'RULE-001-HARDCODED-COLOR',
          severity: 'warning',
          message: `Hardcoded color "${match[0]}" detected. Design tokens should be used instead.`,
          filePath,
          line: index + 1,
          column: match.index + 1,
          evidence: lineText.trim(),
          suggestedFix,
          automatedFixAvailable: Boolean(matchingToken),
        });
      }
    });

    return findings;
  },
};
