import { FlatToken } from '../tokens/types.js';
import { ExporterOptions, GeneratedFile } from './types.js';

export function tokenPathToCssVar(path: string, prefix?: string): string {
  const cleanPath = path.replace(/\./g, '-');
  return prefix ? `--${prefix}-${cleanPath}` : `--${cleanPath}`;
}

export function exportToCss(tokens: FlatToken[], options: ExporterOptions = {}): GeneratedFile {
  const selector = options.selector || ':root';
  const prefix = options.prefix;
  const indent = ' '.repeat(options.indent ?? 2);

  const lines: string[] = [];
  lines.push(`/**`);
  lines.push(` * Generated by NovaDesign Platform`);
  lines.push(` * Source: Central Design System Tokens`);
  lines.push(` */`);
  lines.push(`${selector} {`);

  // Group tokens by category
  const categories = Array.from(new Set(tokens.map((t) => t.category)));

  for (const category of categories) {
    const categoryTokens = tokens.filter((t) => t.category === category);
    lines.push(`${indent}/* --- ${category.toUpperCase()} TOKENS --- */`);

    for (const token of categoryTokens) {
      const varName = tokenPathToCssVar(token.path, prefix);
      const desc = token.description ? ` /* ${token.description} */` : '';
      
      // If token is alias and alias target exists, we can optionally use var() or resolved value
      let val = token.resolvedValue;
      if (token.isAlias && token.aliasTarget && !token.resolvedValue.startsWith('[')) {
        val = `var(${tokenPathToCssVar(token.aliasTarget, prefix)})`;
      }

      lines.push(`${indent}${varName}: ${val};${desc}`);
    }
    lines.push('');
  }

  // Remove trailing blank line if present
  if (lines[lines.length - 1] === '') {
    lines.pop();
  }

  lines.push('}');

  return {
    filename: 'tokens.css',
    content: lines.join('\n') + '\n',
    format: 'css',
  };
}
