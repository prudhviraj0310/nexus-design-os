import { FlatToken } from '../tokens/types.js';
import { tokenPathToCssVar } from './css.js';
import { ExporterOptions, GeneratedFile } from './types.js';

export function exportToTailwind(tokens: FlatToken[], options: ExporterOptions = {}): GeneratedFile {
  const prefix = options.prefix;

  const colorTokens = tokens.filter((t) => t.category === 'color');
  const spacingTokens = tokens.filter((t) => t.category === 'spacing');
  const radiusTokens = tokens.filter((t) => t.category === 'borderRadius');

  const colorsConfig: Record<string, any> = {};
  for (const token of colorTokens) {
    const key = token.path.replace(/^color\./, '').replace(/\./g, '-');
    colorsConfig[key] = `var(${tokenPathToCssVar(token.path, prefix)})`;
  }

  const spacingConfig: Record<string, string> = {};
  for (const token of spacingTokens) {
    const key = token.path.replace(/^spacing\./, '').replace(/\./g, '-');
    spacingConfig[key] = `var(${tokenPathToCssVar(token.path, prefix)})`;
  }

  const radiusConfig: Record<string, string> = {};
  for (const token of radiusTokens) {
    const key = token.path.replace(/^borderRadius\./, '').replace(/\./g, '-');
    radiusConfig[key] = `var(${tokenPathToCssVar(token.path, prefix)})`;
  }

  const lines: string[] = [];
  lines.push(`/**`);
  lines.push(` * Generated by NovaDesign Platform`);
  lines.push(` * Tailwind CSS Theme Configuration`);
  lines.push(` */`);
  lines.push(`module.exports = {`);
  lines.push(`  theme: {`);
  lines.push(`    extend: {`);
  lines.push(`      colors: ${JSON.stringify(colorsConfig, null, 8).replace(/\n\s*}/, '\n      }')},`);
  lines.push(`      spacing: ${JSON.stringify(spacingConfig, null, 8).replace(/\n\s*}/, '\n      }')},`);
  lines.push(`      borderRadius: ${JSON.stringify(radiusConfig, null, 8).replace(/\n\s*}/, '\n      }')},`);
  lines.push(`    },`);
  lines.push(`  },`);
  lines.push(`};`);

  return {
    filename: 'tailwind.tokens.js',
    content: lines.join('\n') + '\n',
    format: 'javascript',
  };
}
