import { FlatToken } from '../tokens/types';
import { ExporterOptions, GeneratedFile } from './types';

function toPascalCase(str: string): string {
  return str
    .replace(/[^a-zA-Z0-9]+(.)/g, (_, chr) => chr.toUpperCase())
    .replace(/^[a-z]/, (chr) => chr.toUpperCase());
}

export function exportToKotlin(tokens: FlatToken[], options: ExporterOptions = {}): GeneratedFile {
  const lines: string[] = [];
  lines.push(`//`);
  lines.push(`// Generated by NovaDesign Platform`);
  lines.push(`// Android Jetpack Compose Design Tokens`);
  lines.push(`//`);
  lines.push('');
  lines.push(`package com.novadesign.tokens`);
  lines.push('');
  lines.push(`import androidx.compose.ui.graphics.Color`);
  lines.push(`import androidx.compose.ui.unit.dp`);
  lines.push(`import androidx.compose.ui.unit.Dp`);
  lines.push('');
  lines.push(`object NovaColors {`);

  const colorTokens = tokens.filter((t) => t.category === 'color');
  for (const token of colorTokens) {
    const propName = toPascalCase(token.path.replace(/^color\./, ''));
    let hex = token.resolvedValue;
    if (hex.startsWith('#')) {
      const cleanHex = hex.replace('#', '');
      const hex8 = cleanHex.length === 6 ? `FF${cleanHex}` : cleanHex;
      lines.push(`    /** ${token.description || token.path} */`);
      lines.push(`    val ${propName} = Color(0x${hex8.toUpperCase()}L)`);
    }
  }

  lines.push(`}`);
  lines.push('');
  lines.push(`object NovaSpacing {`);

  const spacingTokens = tokens.filter((t) => t.category === 'spacing');
  for (const token of spacingTokens) {
    const propName = toPascalCase(token.path.replace(/^spacing\./, ''));
    const numeric = parseFloat(token.resolvedValue) || 0;
    lines.push(`    /** ${token.description || token.path} */`);
    lines.push(`    val ${propName}: Dp = ${numeric}.dp`);
  }

  lines.push(`}`);

  return {
    filename: 'Tokens.kt',
    content: lines.join('\n') + '\n',
    format: 'typescript',
  };
}
