import { FlatToken } from '../tokens/types.js';
import { ExporterOptions, GeneratedFile } from './types.js';

export function exportToTypeScript(tokens: FlatToken[], options: ExporterOptions = {}): GeneratedFile {
  const lines: string[] = [];
  lines.push(`/**`);
  lines.push(` * Generated by NovaDesign Platform`);
  lines.push(` * Source: Central Design System Tokens`);
  lines.push(` */`);
  lines.push('');

  // Structured object tree
  const tree: Record<string, any> = {};
  for (const token of tokens) {
    const parts = token.path.split('.');
    let current = tree;
    for (let i = 0; i < parts.length; i++) {
      const part = parts[i];
      if (i === parts.length - 1) {
        current[part] = token.resolvedValue;
      } else {
        if (!current[part]) current[part] = {};
        current = current[part];
      }
    }
  }

  lines.push(`export const tokens = ${JSON.stringify(tree, null, 2)} as const;`);
  lines.push('');
  lines.push(`export type DesignTokens = typeof tokens;`);
  lines.push('');
  lines.push(`export const tokenPaths = [`);
  for (const token of tokens) {
    lines.push(`  '${token.path}',`);
  }
  lines.push(`] as const;`);
  lines.push('');
  lines.push(`export type TokenPath = typeof tokenPaths[number];`);

  return {
    filename: 'tokens.ts',
    content: lines.join('\n') + '\n',
    format: 'typescript',
  };
}
